    /*
	    - Tracking vs no-tracking
          AsNoTracking на чтении, цена change tracker'а на больших выборках
	    - N+1 и split query
          как ловим(логи запросов, профайлер), `Include` vs `AsSplitQuery`, картезианский взрыв.
	    - Когда уходите в сырой SQL?
          горячие пути, сложная аналитика, bulk-операции
          EF для 90 % CRUD, SQL для остального
          Есть фактура: процедуры, функции, триггеры, индексы на ВТБ Факторинг
	    - Миграции
          только обратно совместимые, expand/contract, не удаляем колонку в том же релизе, где перестали писать





        Tracking или no-tracking — как выбираете?
        Суть ответа: По умолчанию EF отслеживает загруженные сущности, чтобы уметь вычислить изменения при SaveChanges. Для запросов на чтение это лишняя работа: строится снимок состояния, растёт потребление памяти, замедляется материализация. Поэтому все read-only сценарии — AsNoTracking, а на «читающих» контекстах разумно ставить NoTrackingWithIdentityResolution или менять поведение по умолчанию на уровне контекста. Tracking оставляем там, где реально меняем граф объектов и хотим, чтобы EF сам собрал UPDATE. Отдельно: DbContext — короткоживущий и не потокобезопасный, никакого шаринга между запросами.
        Опереться на кейс: МКБ — микросервисы на ASP.NET Core с EF Core, где чтение и запись разведены; РГС — проектирование моделей и API-методов личного кабинета.
        Не говорить: «AsNoTracking всегда быстрее, ставим везде» — на сценариях записи это приведёт к ручной возне с состояниями.

        Как ловите и лечите N+1?
        Суть ответа: Ловим не глазами, а логами и метриками: включённое логирование команд EF на тестовом контуре, счётчик запросов на операцию, а на проде — трейсы, где N+1 виден как пачка одинаковых спанов БД внутри одного запроса. Причины типовые: ленивая загрузка навигационных свойств в цикле, проекция после материализации, обращение к коллекции внутри foreach. Лечится Include/ThenInclude либо, что чаще правильнее, проекцией в DTO через Select — тогда SQL забирает ровно нужные колонки. Ленивую загрузку в веб-сервисах предпочитаю не включать вовсе, чтобы проблема не появлялась.
        Опереться на кейс: РГС — оптимизация существующих решений и рефакторинг по SOLID/DRY; МКБ — рефакторинг legacy-кодовой базы монолита, где N+1 был одним из типовых находок.
        Не говорить: «просто добавляем Include везде» — это ведёт к декартову взрыву.

        Split query или single query?
        Суть ответа: При Include нескольких коллекций EF по умолчанию делает один JOIN-запрос, и строки размножаются по декартову произведению: две коллекции по 100 элементов дают 10 000 строк и тяжёлую материализацию. AsSplitQuery разбивает это на несколько запросов — по одному на коллекцию — и обычно резко снижает объём передаваемых данных. Плата: несколько round-trip и отсутствие единого снимка данных вне явной транзакции, то есть возможна несогласованность между запросами. Правило: одна коллекция — single, несколько коллекций или большие наборы — split, а решение подтверждается замером на реальных объёмах.
        Опереться на кейс: ВТБ Факторинг — миграция и валидация больших объёмов данных, где стоимость лишних строк видна сразу.
        Не говорить: «включили split глобально, стало быстрее» без понимания про согласованность.

        Когда бросаете EF и пишете сырой SQL или берёте Dapper?
        Суть ответа: EF хорош для CRUD и работы с графом агрегата. Ухожу в SQL там, где EF генерирует неоптимальный план или не выражает нужную конструкцию: массовые операции, оконные функции, рекурсивные CTE, сложная аналитика, bulk insert/update, хинты и работа с временными таблицами. Для тяжёлого чтения удобен Dapper — минимальный оверхед и полный контроль над запросом; частая схема — EF на запись, Dapper на чтение. Ключевое — это осознанное решение по результатам профилирования и плана запроса, а не вкусовое.
        Опереться на кейс: ВТБ Факторинг — SQL-процедуры, функции, триггеры, индексы в связке с EF Core; в старых проектах — LinkedServers и тяжёлые запросы на MS SQL.
        Не говорить: «EF медленный, поэтому всё пишем руками».

        Как катите миграции на проде, чтобы не сломать откат?
        Суть ответа: Правило — схема БД всегда совместима с двумя соседними версиями приложения. Практика: expand-contract. Сначала expand — добавляем новую колонку nullable или с дефолтом, новый индекс, пишем в обе, читаем из старой; выкатываем код, который умеет и то и другое; затем переключаем чтение; и только отдельным релизом, убедившись, что откат уже не потребуется, делаем contract — удаляем старое. Прямых ломающих изменений в одном релизе с кодом не делаем, потому что откат кода тогда невозможен без отката данных. Тяжёлые операции — создание индексов CONCURRENTLY в PostgreSQL, backfill батчами, чтобы не держать долгую блокировку.
        Опереться на кейс: ВТБ Факторинг — миграция критичных данных с минимальным временем простоя и утилита автоматической валидации, сократившая время проверки на 40%; в РГС — подготовка релизных веток и скриптов изменений БД по Git-Flow.
        Не говорить: «выкатываем миграцию вместе с кодом, откатываем бэкапом».

        Индексы и план запроса — как работаете?
        Суть ответа: Отправная точка — фактический план: EXPLAIN (ANALYZE, BUFFERS) в PostgreSQL, актуальный план и статистика ожиданий в MS SQL. Смотрим на seq scan по большим таблицам, неверную оценку кардинальности, сортировки на диске. Индексы проектируются под конкретные предикаты: составной индекс с правильным порядком колонок, покрывающий индекс с INCLUDE, частичный индекс под узкую выборку. Помним про цену: каждый индекс замедляет запись и занимает место, поэтому неиспользуемые индексы вычищаются по статистике использования. Отдельная типовая ловушка — функция или приведение типа над колонкой в предикате, убивающие индекс.
        Опереться на кейс: ВТБ Факторинг — оптимизация миграции: время переноса 1000 записей сокращено с 510 до 180 секунд, в 2,8 раза (совместно с Валерием).
        Не говорить: «повесили индексы на все колонки, которые участвуют в фильтрах».

        Транзакции и уровни изоляции — что применяете?
        Суть ответа: Дефолт в PostgreSQL — Read Committed, и для большинства сценариев его достаточно; в MS SQL полезно включать READ_COMMITTED_SNAPSHOT, чтобы читатели не блокировали писателей. Более строгие уровни (Repeatable Read, Serializable) берём точечно, понимая цену: рост числа конфликтов и необходимость обрабатывать ошибки сериализации ретраем. В конкурентных сценариях чаще выбираю оптимистическую блокировку через версию строки (rowversion / xmin, в EF — конкурентный токен), а не длинные транзакции. Главное правило — транзакция короткая и не содержит внешних вызовов: HTTP-запрос внутри транзакции держит блокировки на время чужого таймаута.
        Опереться на кейс: МКБ и ВТБ Факторинг — операции миграции и обработки данных, где длинные транзакции пришлось разбивать на батчи ради минимизации блокировок.
        Не говорить: «ставим Serializable, чтобы наверняка»
    */
}
